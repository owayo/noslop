pub(super) static P03: PhraseSpec = PhraseSpec {
    meta: RuleMeta {
        id: "P03",
        name: "AI_CONJUNCTION",
        title: "空疎な接続",
        lane: Lane::Slop,
        signal: Some(Signal::Weak),
        default_severity: Info,
        summary: "「このように」「このような中」のような、前の内容を機械的に束ねる接続を指摘する",
        explanation: r"### 何を見るか

「このように」「このような中」のように、前の内容をひとまとめにして次へ渡す接続を探します。同じブロック内で対応する「」・『』・“”・二重引用符の内側に完全に収まる一致と、開き引用符の直後の一致は、語句への言及として除きます。意味による判定ではないため、引用された発言で実際に使われた定型句も指摘しません。

### なぜ問題か

前の段落で何が述べられたかに関係なく使える語で、書き手の思考の跡が残りません。段落の頭がこの手の接続ばかりになると、論理のつながりを語で取り繕っているように読めます。言い換えで同じ内容を繰り返す「つまり、〜ということです」も、情報を増やさずに字数だけを増やします。

### 直し方

接続語を外しても前後がつながるか確かめます。つながらないなら、前の段落の具体的な事実や疑問を受けて次の話を始めます。

### 例

- 直す前: このように、在庫管理の自動化には多くの利点がある。
- 直した後: 発注の入力が要らなくなり、欠品は四半期で 12 件から 2 件に減った。

### 根拠

人の文書 164 本 (一般・技術・業務・随筆) では 28 本 (17.1%)、書式を保った人の技術記事 130 本では 8 本 (6.2%) に反応し、生成文書 (2025 年頃のモデルの 374 本で 22 本・5.9%、2026 年のモデルの 1,339 本で 77 本・5.8%) と同じかそれ以上でした。文書を約 1,300 字ずつに切って長さをそろえても、人の文書のほうが多く反応しました。人の白書や技術記事は、節の要約や、例や図を指す用法 (「このように設定すると」) でこの語をよく使います。文書の結び (地の文の最後の 2 段落) に限っても、人 164 本中 4 本・2026 年の生成 1,339 本中 33 本で分かれなかったので、P01 のように結びに絞ることもしていません。「このような中」は人の文書にだけ出ました。「つまり、〜ということです」は未校正の項目です。

手掛かりの強さは「弱い」です。人の文書 440 本と生成文書 390 本で測ると、指摘が出た文書は人 52 本・生成 26 本で、人の文書のほうが多くありました。",
    },
    entries: P03_ENTRIES,
    message: "「{m}」は前の内容を機械的に束ねる接続です",
    hint: "接続語に頼らず、前の内容の具体的な事実や疑問から次の話へつないでください",
};

