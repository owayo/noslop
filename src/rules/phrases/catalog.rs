pub(super) static P02: PhraseSpec = PhraseSpec {
    meta: RuleMeta {
        id: "P02",
        name: "AI_PREFACE",
        title: "定型の前置き・予告",
        lane: Lane::Slop,
        signal: Some(Signal::Weak),
        default_severity: Info,
        summary: "「見ていきましょう」「解説していきます」のような、中身を運ばない前置きと予告を指摘する",
        explanation: r"### 何を見るか

「それでは、」「ここで注目したいのは」「見ていきましょう」「解説していきます」のように、これから何をするかを予告するだけの言い回しを探します。文を「最後にまとめます。」で言い切る予告も探します。同じブロック内で対応する「」・『』・“”・二重引用符の内側に完全に収まる一致と、開き引用符の直後の一致は、語句への言及として除きます。意味による判定ではないため、引用された発言で実際に使われた定型句も指摘しません。

### なぜ問題か

予告は次の話題へ移る合図として便利ですが、情報を 1 つも運びません。人が書く文章では、話題が変わるきっかけはふつう新しい事実や問いで、合図の言葉だけで次へ進むことはあまりありません。予告が続くと、読み手は本題にたどり着くまで待たされます。

### 直し方

予告の一文を消し、伝えたい内容そのものから書き始めます。前の段落とのつながりは、合図の語ではなく内容で作ります。

### 例

- 直す前: それでは、新しい料金体系を見ていきましょう。
- 直した後: 新しい料金体系では、月額の区分が 3 段階から 2 段階になる。

### 根拠

「それでは、」「見ていきましょう」「解説していきます」などの前置きの語句をまとめて数えると、人の文書 164 本 (一般・技術・業務・随筆) のうち 13 本 (7.9%) に反応し、生成文書 (2025 年頃のモデルの 374 本で 8 本・2.1%、2026 年のモデルの 1,339 本で 41 本・3.1%) より多く出ました。書式を保った人の技術記事 130 本でも 10 本 (7.7%) に反応しています。「見ていきましょう」は人の技術記事 130 本中 8 本、2026 年の生成の技術文書 328 本中 11 本でした。「さて、」は人の文書 15 本 (9.1%) に対し、生成文書では 1〜2% です。人の解説や講演でも話題を移す合図として普通に使う言い回しなので、どの語句も情報で扱います。「今回は〜について紹介します」「本記事では〜」「本報告書では」「本レポートは」「まず初めに、」「近年、〜ますます」は未校正の項目です。「本報告書では」「本レポートは」は、調査レポートの形で書かせた生成文書の書き出しに多く出ましたが、官公庁や企業の報告書では人も使う定型なので、情報で扱います。「最後にまとめます」は、生成を開示した記事 1 本に出た予告です (人の文書 171 本には 0 本)。件数が少なく校正できないため、情報で扱います。「最後に」だけでは人の文章のほうに多く出るので、文を「まとめます」で言い切る形に限っています。

手掛かりの強さは「弱い」です。人の文書 440 本と生成文書 390 本で測ると、指摘が出た文書は人 76 本・生成 60 本で、人の文書のほうが多くありました。項目では、「本記事では」は中程度です (人 11 本・生成 20 本)。「本報告書では」「本レポートは」(人 0 本・生成 18 本) と、「本稿では〜を紹介」のように中身を予告する形 (人 2 本・生成 12 本) は強い手掛かりです。",
    },
    entries: P02_ENTRIES,
    message: "「{m}」は中身を運ばない前置き・予告です",
    hint: "予告を消して、伝えたい内容そのものから書き始めてください",
};

