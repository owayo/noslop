pub(super) static P19: PhraseSpec = PhraseSpec {
    meta: RuleMeta {
        id: "P19",
        name: "HYPE",
        title: "誇張表現",
        lane: Lane::Slop,
        signal: Some(Signal::Moderate),
        default_severity: Info,
        summary: "「革命的」「ゲームチェンジャー」「飛躍的に」のような、根拠を示さずに効果を大きく言う誇張を指摘する",
        explanation: r"### 何を見るか

「革命的」「ゲームチェンジャー」「究極の」「パラダイムシフト」「飛躍的に」「無限の可能性」のように、効果や新しさを大きく言い立てる言葉を探します。「民主化運動」「メソッドを再定義する」のような普通の用法は拾いません。同じブロック内で対応する「」・『』・“”・二重引用符の内側に完全に収まる一致と、開き引用符の直後の一致は、語句への言及として除きます。意味による判定ではないため、引用された発言や題名で実際に使われた誇張も指摘しません。

### なぜ問題か

宣伝文の言い回しを大量に学習しているため、生成された文章は製品や手法の説明で大げさな形容に寄りがちです。誇張は数字や比較の代わりにならず、読み手は「どれくらい」「何と比べて」を知りたいまま置いていかれます。誇張が重なるほど、書かれた効果そのものが疑わしく見えます。

### 直し方

効果を数値か比較で示します。比べる材料がないなら、形容を外して起きたことを淡々と書きます。

### 例

- 直す前: この機能は、承認業務を劇的に変える革命的な仕組みです。
- 直した後: この機能で、承認にかかる時間は平均 2 日から半日になった。

### 根拠

宣伝文や広告の原稿では意図して使うこともあるので、残すなら理由を書いてください。

手掛かりの強さは中程度です。人の文書 440 本と生成文書 390 本で測ると、指摘が出た文書は人 11 本・生成 18 本でした。項目のうち「圧倒的な」(人 2 本・生成 7 本) は強い手掛かりです。",
    },
    entries: P19_ENTRIES,
    message: "「{m}」は根拠を示さずに効果を大きく言う誇張表現です",
    hint: "効果を数値や比較で示すか、形容を外して起きたことを書いてください",
};

