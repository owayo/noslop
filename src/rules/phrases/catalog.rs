//! 語句辞書で動くルール (P01〜P12、P18・P19) の定義。
//!
//! どの項目も既定で動く。重大度は直す優先度で、人間の文章にも一定数出た語句は情報 (info) にする。
//! AI 臭さのレーンの項目は、手掛かりの強さ ([`Signal`]) をルールの値から継ぐ。項目ごとに測った
//! 強さがルールと違う項目と、ルールの校正の基準より軽い重大度の項目 (警告のルールにある情報の
//! 項目。ルールの強さの測定に入らない) は、[`Entry::with_signal`] で自分の強さを書く。

use crate::diagnostic::{Lane, Severity, Signal};
use crate::rules::RuleMeta;

use super::engine::{Entry, PhraseSpec};

use Severity::{Info, Warning};

// ---------------------------------------------------------------------------
// P01 AI_CONCLUSION
// ---------------------------------------------------------------------------

const P01_ENTRIES: &[Entry] = &[
    Entry::lit("と言えるでしょう", Warning),
    Entry::lit("と言えるだろう", Warning),
    Entry::lit("と言えます", Warning),
    Entry::lit("ということになるでしょう", Warning),
    Entry::lit("のではないでしょうか", Warning),
    Entry::lit("結論から言うと", Warning),
    Entry::lit("結論として", Warning),
    // 要約を導く形に限る。引用内は文分割されないため、文末記号の後も文頭として読む。
    // 操作先の「〜に」や、結果の述語が直接続く条件文は当てない。
    Entry::re(
        r"(?:(?:^|[。．｡.！？!?])[\s\p{Ps}\p{Pe}\p{Pi}\p{Pf}\x22\x27]*(?:(?:最後に|簡単に|端的に|一言で)[\s、]*)?|(?:以上|これまでの内容|ここまでの議論|要点|概要|結論|全体|結果|コツ|ルール)を\s*)(?P<m>まとめると)\s*(?:[、,，。．｡.！？!?]|$|次のとおり|以下のよう)",
        Warning,
    ),
    Entry::lit("総じて", Warning),
    // 以下の情報の項目は、ルールの強さ (警告で測った値) を継がずに自分の強さを持つ。
    // 一般向けの人の記事の結び (「ぜひ〜してみてはいかがでしょうか」) にも同じくらい出る
    Entry::lit("いかがでしたか", Info).with_signal(Signal::Moderate),
    Entry::lit("いかがでしょうか", Info).with_signal(Signal::Moderate),
    Entry::re(r"(?:と言っても)?過言では(?:ない|ありません)", Info).with_signal(Signal::Moderate),
    Entry::re(
        r"以上、.{1,40}?(?:について|を)(?:解説|紹介|説明)しました",
        Info,
    )
    .with_signal(Signal::Moderate),
    // 校正済みの「結論から言うと」の言い換え。生成文書で見つかった形だけを入れる
    // (「結論から申し上げると」のような、見つかっていない形は入れない)
    Entry::re(r"結論から(?:言えば|申し上げますと|述べると)", Info).with_signal(Signal::Moderate),
];

pub(super) static P01: PhraseSpec = PhraseSpec {
    meta: RuleMeta {
        id: "P01",
        name: "AI_CONCLUSION",
        title: "結論の押し付け・まとめ口調",
        lane: Lane::Slop,
        signal: Some(Signal::Strong),
        default_severity: Warning,
        summary: "文書の結びの「と言えるでしょう」「まとめると」のような、結論を定型句で押し付ける締めを指摘する",
        explanation: r"### 何を見るか

文書の結び (日本語を含む地の文の、最後の 2 段落) で、「と言えるでしょう」「のではないでしょうか」「まとめると」「総じて」のように、結論を定型句で包んで差し出す言い回しを探します。結びの段落の後ろに見出し・箇条書き・表・コードが続いても、その手前の段落を結びとみなします。本文の途中の問いかけ (「〜な方も多いのではないでしょうか」) や節の途中のまとめは指摘しません。文書の構造が要るので、コードのコメントや表計算のセルのような断片には当てません。「まとめると」は、文頭 (「最後に」「簡単に」「端的に」「一言で」を含む) か、「以上を」「要点を」「コツを」「ルールを」など要約対象の直後で、読点・文末・「次のとおり」「以下のよう」が続く形に限ります。「処理を関数にまとめると、確認しやすい」のような操作の条件文は指摘しません。「いかがでしたか」「いかがでしょうか」と、「結論から言うと」の言い換えの「結論から言えば」「結論から申し上げますと」「結論から述べると」も、情報の指摘として探します。同じブロック内で対応する「」・『』・“”・二重引用符の内側に完全に収まる一致と、開き引用符の直後の一致は、語句への言及として除きます。意味による判定ではないため、引用された発言で実際に使われた定型句も指摘しません。

### なぜ問題か

要約の定型として大量に学習された言い回しで、生成された文章ほど文書の結びに現れます。読み手が判断する前に結論だけを先回りして渡すので、言い切ってもいないのに押し付けがましく響きます。「のではないでしょうか」は断定を避ける逃げ道として使われやすく、重ねるほど意見のない文章に見えます。

### 直し方

定型句を外して言い切るか、結論を支える事実や数値をそのまま書きます。言い切れないなら、何が分かっていないのかを書きます。

### 例

- 直す前: この改善によって、チームの負担は大きく減ったと言えるでしょう。
- 直した後: この改善で、週次の手作業は 6 時間から 1 時間に減った。

### 根拠

警告の語句は、人間とAIのコーパスで出方を確かめたものです。位置を問わずに数えると、人の文書 176 本のうち 23 本 (13.1%) に反応し、生成文書 (2025 年頃のモデルなどの 390 本で 48 本・12.3%、2026 年のモデルの 1,339 本で 142 本・10.6%) と変わりませんでした。人の文書では、同じ語句が本文の途中の問いかけや節のまとめに多く出ます。生成文書の結論の定型句は文書の最後の段落に集まるので、結びに限りました。結びに限ると人の文書は 0 本になり、生成文書は 27 本 (6.9%) と 70 本 (5.2%) が残ります。この条件を決めた後に集めた、書式を保った人の技術記事 130 本では、12 本から 2 本に減りました。さらに集めた書式を保った人の一般向けの記事 108 本では 8 本 (7.4%) に反応し、どれも結びの「いかがでしょうか」(「ぜひ〜してみてはいかがでしょうか」) と「いかがでしたか」でした。この 2 つは、2026 年のモデルの一般向けの文書 340 本の 24 本 (7.1%)、2025 年頃のモデルなどの一般向けの文書 201 本の 10 本 (5.0%) と同じくらい人の記事にも出ます。人の文書全体 (414 本) でも 9 本 (2.2%) と、生成文書 (1,339 本で 34 本・2.5%、390 本で 12 本・3.1%) と変わらないので、警告から外して情報にしました。警告の語句だけで数えると、人の文書 176 本で 0 本、書式を保った人の技術記事で 1 本 (0.8%)、一般向けの記事で 0 本になり、生成文書は 390 本で 15 本 (3.8%)、1,339 本で 37 本 (2.8%) が残ります。一般向けの記事 108 本はこの判断にも使ったので、ここでの値は独立した検証の結果ではありません。結びの段落の数は、1 段落にすると生成文書の検出が減り、3 段落にすると人の文書にも反応し始めたため、2 段落にしています。「まとめると」は、人も要約に使うため、この表現だけで AI の文章とは判断できません。要約対象と読点がそろった条件文も残ることがあるので、文脈で判断してください。業務メールの「ご都合はいかがでしょうか」のように自然な用法もあるので、文脈で判断してください。「過言ではない」と「以上、〜について解説しました」は、校正していないので情報で扱います。「結論から言えば」「結論から申し上げますと」「結論から述べると」は、校正済みの「結論から言うと」の言い換えのうち、生成文書で実際に見つかった形だけを入れたものです。人の文書 171 本には出ず、生成文書 390 本のうち 5 本と Deep Research の出力 33 本のうち 1 本に出ましたが、件数が少なく校正できないため、情報で扱います。

手掛かりの強さは「強い」です。人の文書 440 本と生成文書 390 本で測ると、警告以上の指摘が出た文書は人 1 本・生成 15 本でした。情報の項目はどれも中程度です。「いかがでしょうか」は人 8 本・生成 12 本で、ほかの項目は件数が少なく測れません (「いかがでしたか」は人 2 本・生成 0 本)。",
    },
    entries: P01_ENTRIES,
    message: "「{m}」は結論を定型句で押し付ける締めです",
    hint: "定型句を外して言い切るか、結論を支える事実や数値を書いてください",
};

